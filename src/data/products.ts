export const products: Product[] = rows.map(
  ([id, ru, en, dr, de, category, price, flavor], i) => ({
    id,
    name: { ru, en },
    description: { ru: dr, en: de },
    category,
    price,
    flavor,
    image:
      category === "desserts" ? `/assets/${id}.webp` : flavors[flavor].image,
    sizes:
      category === "desserts"
        ? []
        : category === "coffee"
          ? [250, 350]
          : [350, 500],
    badge: i % 7 === 0 ? "popular" : i % 5 === 0 ? "new" : undefined,
  }),
);
export const priceFor = (product: Product, size: number) =>
  product.price +
  (product.sizes.length > 1 && size === product.sizes[1] ? 70 : 0);
